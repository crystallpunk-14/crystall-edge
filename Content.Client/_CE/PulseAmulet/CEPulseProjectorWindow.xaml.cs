using Content.Client.Pinpointer.UI;
using Content.Shared._CE.PulseAmulet;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._CE.PulseAmulet;

[GenerateTypedNameReferences]
public sealed partial class CEPulseProjectorWindow : DefaultWindow
{
    [Dependency] private IEntityManager _entManager = default!;

    private static readonly SpriteSpecifier.Texture MarkerBlip =
        new(new ResPath("/Textures/Interface/NavMap/beveled_circle.png"));

    public CEPulseProjectorWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void SetMap(EntityUid? mapUid)
    {
        ZNavMap.MapUid = mapUid;
        ZNavMap.ForceNavMapUpdate();
    }

    public void UpdateState(CEPulseProjectorBoundUserInterfaceState state)
    {
        ZNavMap.TrackedEntities.Clear();

        var texture = _entManager.System<SpriteSystem>().Frame0(MarkerBlip);

        // Markers are anonymous, so they are keyed by index rather than by the amulet entity.
        for (var i = 0; i < state.Markers.Count; i++)
        {
            var marker = state.Markers[i];
            var coords = _entManager.GetCoordinates(marker.Coordinates);
            var (color, blinks) = marker.Status switch
            {
                CEPulseMarkerStatus.Critical => (Color.Yellow, true),
                CEPulseMarkerStatus.Dead => (Color.Red, true),
                CEPulseMarkerStatus.Removed => (Color.Gray, false),
                _ => (Color.LimeGreen, false),
            };

            ZNavMap.TrackedEntities[new NetEntity(int.MinValue + i)] = new NavMapBlip(coords, texture, color, blinks, false);
        }
    }
}
