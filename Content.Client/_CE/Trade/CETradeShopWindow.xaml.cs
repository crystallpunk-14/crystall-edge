using System.Linq;
using Content.Client._CE.UserInterface;
using Content.Shared._CE.Trade;
using Content.Shared._CE.Trade.Prototypes;
using Content.Shared._CE.Workbench.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._CE.Trade;

/// <summary>
/// Every offer of a trade shop, grouped by category; offers the user can make right now go first in each group.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CETradeShopWindow : DefaultWindow
{
    [Dependency] private IEntityManager _entity = default!;
    [Dependency] private IPrototypeManager _prototype = default!;

    public event Action<ProtoId<CETradeOfferPrototype>>? OnTrade;

    private const int AllCategoryId = -1;

    private readonly CESharedTradeSystem _trade;

    private CETradeShopUiState? _state;
    private string _searchFilter = string.Empty;
    private readonly List<CEWorkbenchRecipeCategoryPrototype?> _categories = new();

    public CETradeShopWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _trade = _entity.System<CESharedTradeSystem>();

        SearchBar.OnTextChanged += _ =>
        {
            _searchFilter = SearchBar.Text.Trim().ToLowerInvariant();
            UpdateOffers();
        };

        OptionCategories.OnItemSelected += args =>
        {
            OptionCategories.SelectId(args.Id);
            UpdateOffers();
        };
    }

    public void UpdateState(CETradeShopUiState state)
    {
        _state = state;
        // Keep the label, replace the coins
        while (BalanceBox.ChildCount > 1)
        {
            BalanceBox.RemoveChild(BalanceBox.GetChild(1));
        }

        BalanceBox.AddChild(new CEPriceControl(state.Balance));

        var selected = OptionCategories.SelectedId >= 0 && OptionCategories.SelectedId < _categories.Count
            ? _categories[OptionCategories.SelectedId]?.ID
            : null;

        // Uncategorized offers (null) are listed first, without a header
        _categories.Clear();
        foreach (var entry in state.Entries)
        {
            var category = GetCategory(entry);
            if (!_categories.Contains(category))
                _categories.Add(category);
        }

        _categories.Sort((a, b) =>
        {
            if (a is null || b is null)
                return a is null ? (b is null ? 0 : -1) : 1;

            return b.Priority != a.Priority ? b.Priority.CompareTo(a.Priority) : string.CompareOrdinal(a.ID, b.ID);
        });

        OptionCategories.Clear();
        OptionCategories.AddItem(Loc.GetString("ce-recipe-category-all"), AllCategoryId);
        for (var i = 0; i < _categories.Count; i++)
        {
            if (_categories[i] is not { } category)
                continue;

            OptionCategories.AddItem(Loc.GetString(category.Name), i);
            if (category.ID == selected)
                OptionCategories.SelectId(i);
        }

        UpdateOffers();
    }

    private void UpdateOffers()
    {
        OffersContainer.RemoveAllChildren();
        if (_state is null)
            return;

        for (var i = 0; i < _categories.Count; i++)
        {
            if (OptionCategories.SelectedId != AllCategoryId && OptionCategories.SelectedId != i)
                continue;

            var category = _categories[i];
            var entries = _state.Entries
                .Where(e => GetCategory(e) == category && MatchesSearch(e))
                .Select(e => (Entry: e, Offer: _prototype.Index(e.Offer)))
                .OrderByDescending(e => e.Entry.Missing is null)
                .ThenBy(e => e.Entry.PayPrice)
                .ThenBy(e => _trade.GetOfferName(e.Offer))
                .ToList();

            if (entries.Count == 0)
                continue;

            if (category is not null)
            {
                var header = new RichTextLabel { Margin = new Thickness(5) };
                header.SetMessage(Loc.GetString(category.Name));
                OffersContainer.AddChild(header);
            }

            foreach (var (entry, offer) in entries)
            {
                var control = new CETradeShopOfferControl(entry, offer);
                control.OnTrade += id => OnTrade?.Invoke(id);
                OffersContainer.AddChild(control);
            }
        }
    }

    private CEWorkbenchRecipeCategoryPrototype? GetCategory(CETradeShopEntry entry)
    {
        if (!_prototype.TryIndex(entry.Offer, out var offer) || offer.Category is not { } category)
            return null;

        return _prototype.TryIndex(category, out var indexed) ? indexed : null;
    }

    private bool MatchesSearch(CETradeShopEntry entry)
    {
        if (_searchFilter.Length == 0)
            return true;

        return _prototype.TryIndex(entry.Offer, out var offer)
               && _trade.GetOfferName(offer).ToLowerInvariant().Contains(_searchFilter);
    }
}
