using System.Linq;
using Content.Client._CE.Skill.Ui;
using Content.Shared.Humanoid.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._CE.Lobby.UI.Species;

/// <summary>
/// Lobby species tab: a grid of round-start species tiles and a details panel describing the hovered
/// species, or the picked one when nothing is hovered, together with its innate skills.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CESpeciesPicker : BoxContainer
{
    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private IPrototypeManager _proto = default!;

    private readonly SpriteSystem _sprite;

    private readonly Dictionary<ProtoId<SpeciesPrototype>, CESpeciesButton> _buttons = new();
    private ProtoId<SpeciesPrototype>? _selected;
    private ProtoId<SpeciesPrototype>? _hovered;
    private ProtoId<SpeciesPrototype>? _shown;

    /// <summary>
    /// Raised when a species tile other than the picked one is clicked.
    /// </summary>
    public event Action<ProtoId<SpeciesPrototype>>? OnSpeciesSelected;

    public CESpeciesPicker()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _sprite = _entMan.System<SpriteSystem>();
    }

    /// <summary>
    /// The round-start species in picker order.
    /// </summary>
    public List<SpeciesPrototype> GetAvailableSpecies()
    {
        return _proto.EnumeratePrototypes<SpeciesPrototype>()
            .Where(s => s.RoundStart)
            .OrderBy(s => Loc.GetString(s.Name), StringComparer.CurrentCultureIgnoreCase)
            .ToList();
    }

    /// <summary>
    /// Rebuilds the grid - call when species prototypes change.
    /// </summary>
    public void Populate(ProtoId<SpeciesPrototype>? selected)
    {
        SpeciesGrid.RemoveAllChildren();
        _buttons.Clear();

        foreach (var species in GetAvailableSpecies())
        {
            var id = new ProtoId<SpeciesPrototype>(species.ID);
            var button = new CESpeciesButton(id, GetIcon(species.Icon), GetIcon(species.HoveredIcon));

            button.OnPressed += _ =>
            {
                if (_selected != id)
                    OnSpeciesSelected?.Invoke(id);
            };
            button.OnMouseEntered += _ => SetHovered(id);
            button.OnMouseExited += _ =>
            {
                if (_hovered == id)
                    SetHovered(null);
            };

            _buttons[id] = button;
            SpeciesGrid.AddChild(button);
        }

        if (_hovered is { } hovered && !_buttons.ContainsKey(hovered))
            _hovered = null;

        _shown = null;
        SetSelection(selected);
    }

    /// <summary>
    /// Updates tile states after the picked species changed, without rebuilding the grid.
    /// </summary>
    public void SetSelection(ProtoId<SpeciesPrototype>? selected)
    {
        _selected = selected;

        foreach (var (id, button) in _buttons)
        {
            button.SetState(id == _selected, false);
        }

        UpdateDetails();
    }

    private void SetHovered(ProtoId<SpeciesPrototype>? species)
    {
        _hovered = species;
        UpdateDetails();
    }

    private void UpdateDetails()
    {
        var id = _hovered ?? _selected;
        if (id == _shown)
            return;

        _shown = id;

        if (id is null || !_proto.Resolve(id.Value, out var species))
        {
            DetailsBox.Visible = false;
            DetailsHint.Visible = true;
            return;
        }

        DetailsBox.Visible = true;
        DetailsHint.Visible = false;

        DetailsIcon.Texture = GetIcon(species.HoveredIcon ?? species.Icon);
        DetailsName.Text = Loc.GetString(species.Name);
        DetailsDescription.SetMessage(species.Description is { } description
            ? FormattedMessage.FromMarkupPermissive(Loc.GetString(description))
            : new FormattedMessage());
        DetailsDescription.Visible = species.Description is not null;

        SkillsList.RemoveAllChildren();
        foreach (var skill in species.Skills)
        {
            var control = new CESkillControl();
            control.SetSkill(skill);
            SkillsList.AddChild(control);
        }

        SkillsBox.Visible = species.Skills.Count > 0;
    }

    private Texture? GetIcon(SpriteSpecifier? icon)
    {
        return icon is not null ? _sprite.Frame0(icon) : null;
    }
}
