using System.Numerics;
using Content.Shared._CE.LockKey;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._CE.LockKey.UI;

[GenerateTypedNameReferences]
public sealed partial class CELockKeyForgeWindow : DefaultWindow
{
    public event Action<List<int>>? OnShapeSelected;

    /// <summary>
    /// Delay after the last edit before the shape is sent, so quick clicking produces a single request.
    /// </summary>
    private const float ApplyDelay = 0.5f;

    private List<int> _editedShape = new();
    private int _maxComplexity = 1;
    private float? _applyTimer;

    public CELockKeyForgeWindow()
    {
        RobustXamlLoader.Load(this);

        AddToothButton.OnPressed += _ =>
        {
            _editedShape.Add(CESharedLockKeySystem.MinHeight);
            ApplyShape();
        };
        RemoveToothButton.OnPressed += _ =>
        {
            _editedShape.RemoveAt(_editedShape.Count - 1);
            ApplyShape();
        };
    }

    public void UpdateState(CELockKeyForgeUiState state)
    {
        _maxComplexity = state.MaxComplexity;
        ResultView.SetPrototype(state.Result);

        // Don't overwrite edits that are still waiting to be sent
        if (_applyTimer is not null)
            return;

        _editedShape = new List<int>(state.Shape);
        UpdateEditor();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_applyTimer is null)
            return;

        _applyTimer -= args.DeltaSeconds;
        if (_applyTimer > 0)
            return;

        _applyTimer = null;
        OnShapeSelected?.Invoke(new List<int>(_editedShape));
    }

    public void UpdateTemplates(List<(EntityUid Uid, string Name, List<int> Shape)> templates)
    {
        TemplatesContainer.RemoveAllChildren();
        NoTemplatesLabel.Visible = templates.Count == 0;

        foreach (var template in templates)
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };

            var icon = new SpriteView
            {
                OverrideDirection = Direction.South,
                SetSize = new Vector2(32, 32),
            };
            icon.SetEntity(template.Uid);
            row.AddChild(icon);

            row.AddChild(new Label
            {
                Text = template.Name,
                HorizontalExpand = true,
                ClipText = true,
                Margin = new Thickness(5, 0),
            });
            row.AddChild(new Label { Text = FormatShape(template.Shape) });

            var button = new Button
            {
                HorizontalExpand = true,
                ToolTip = Loc.GetString("ce-lock-forge-ui-template-tooltip"),
                Disabled = template.Shape.Count == 0 || template.Shape.Count > _maxComplexity,
            };
            button.AddChild(row);

            var shape = template.Shape;
            button.OnPressed += _ =>
            {
                _applyTimer = null;
                OnShapeSelected?.Invoke(new List<int>(shape));
            };

            TemplatesContainer.AddChild(button);
        }
    }

    private void UpdateEditor()
    {
        ComplexityLabel.Text = Loc.GetString("ce-lock-forge-ui-complexity", ("count", _editedShape.Count), ("max", _maxComplexity));
        RemoveToothButton.Disabled = _editedShape.Count <= 1;
        AddToothButton.Disabled = _editedShape.Count >= _maxComplexity;

        TeethContainer.RemoveAllChildren();
        for (var i = 0; i < _editedShape.Count; i++)
        {
            var index = i;
            var column = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                Margin = new Thickness(3, 0),
            };

            var up = new Button
            {
                Text = "▲",
                Disabled = _editedShape[index] >= CESharedLockKeySystem.MaxHeight,
            };
            up.OnPressed += _ =>
            {
                _editedShape[index]++;
                ApplyShape();
            };

            var down = new Button
            {
                Text = "▼",
                Disabled = _editedShape[index] <= CESharedLockKeySystem.MinHeight,
            };
            down.OnPressed += _ =>
            {
                _editedShape[index]--;
                ApplyShape();
            };

            column.AddChild(up);
            column.AddChild(new Label
            {
                Text = _editedShape[index].ToString(),
                HorizontalAlignment = HAlignment.Center,
            });
            column.AddChild(down);
            TeethContainer.AddChild(column);
        }
    }

    private void ApplyShape()
    {
        UpdateEditor();
        _applyTimer = ApplyDelay;
    }

    private static string FormatShape(List<int> shape) => string.Join("-", shape);
}
