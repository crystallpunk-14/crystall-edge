/// <summary>
/// Interactive alchemy sandbox for the guidebook. The recipe is replayed by the same
/// <see cref="CEAlchemySystem"/> that the game uses, so the round seed is already accounted for.
/// </summary>
[UsedImplicitly, GenerateTypedNameReferences]
public sealed partial class CEGuideAlchemySandbox : PanelContainer, IDocumentTag, ISearchableControl
{
    /// <summary>
    /// Tuning step of the devices.
    /// </summary>
    private const float TuneStep = 0.05f;

    private const string MixtureReagent = "CEAlchemyMixture";
    private const string MixtureStage = "Bloodstream";

    private static readonly Color PositionColor = Color.FromHex("#4fb59a");
    private static readonly Color PathColor = Color.FromHex("#e08a4a");
    private static readonly Color ModifierColor = Color.FromHex("#b58cf0");
    private static readonly Color MutedColor = Color.FromHex("#8e9a9a");

    [Dependency] private IPrototypeManager _prototype = default!;
    [Dependency] private IEntitySystemManager _entSys = default!;
    [Dependency] private IClipboardManager _clipboard = default!;
    [Dependency] private ILogManager _logManager = default!;

    private readonly CEAlchemySystem _alchemy;
    private readonly ISawmill _sawmill;

    private readonly List<(ProtoId<ReagentPrototype> Reagent, FixedPoint2 Amount)> _steps = new();
    private readonly Dictionary<ProtoId<ReagentPrototype>, Button> _paletteButtons = new();
    private ProtoId<ReagentPrototype>? _selected;
    private float _amount = 5f;
    private float _dose;
    private bool _doseFollowsMax = true;
    private bool _updatingDose;
    private float _tune;

    public CEGuideAlchemySandbox()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        MouseFilter = MouseFilterMode.Stop;
        _alchemy = _entSys.GetEntitySystem<CEAlchemySystem>();
        _sawmill = _logManager.GetSawmill("guidebook.ce_alchemy_sandbox");

        BuildPalette();

        Map.OnDotClicked += reagent =>
        {
            var id = new ProtoId<ReagentPrototype>(reagent);
            if (!_paletteButtons.TryGetValue(id, out var button))
                return;

            Select(id);
        };

        AmountSlider.OnValueChanged += _ =>
        {
            _amount = MathF.Round(AmountSlider.Value * 10f) / 10f;
            AmountLabel.Text = FormatAmount(_amount);
            UpdatePreview();
        };
        AmountLabel.Text = FormatAmount(_amount);
        DoseSlider.OnValueChanged += _ =>
        {
            if (_updatingDose)
                return;

            _dose = MathF.Round(DoseSlider.Value * 10f) / 10f;
            _doseFollowsMax = DoseSlider.Value >= DoseSlider.MaxValue - 0.05f;
            Rebuild();
        };
        AddButton.Disabled = _selected == null;
        AddButton.OnPressed += _ =>
        {
            if (_selected is { } selected)
                AddStep(selected);
        };
        CopyButton.OnPressed += _ => _clipboard.SetText(BuildRecipeText());
        TuneSlider.OnValueChanged += _ =>
        {
            _tune = MathF.Round(TuneSlider.Value / TuneStep) * TuneStep;
            Rebuild();
        };

        Rebuild();
    }

    public bool CheckMatchesSearch(string query)
    {
        return this.ChildrenContainText(query);
    }

    public void SetHiddenState(bool state, string query)
    {
        Visible = CheckMatchesSearch(query) ? state : !state;
    }

    public bool TryParseTag(Dictionary<string, string> args, [NotNullWhen(true)] out Control? control)
    {
        control = this;
        return true;
    }

    private void BuildPalette()
    {
        Palette.RemoveAllChildren();
        _paletteButtons.Clear();

        var reagents = new List<ReagentPrototype>();
        foreach (var reagent in _prototype.EnumeratePrototypes<ReagentPrototype>())
        {
            if (reagent.AlchemyEffects.Count > 0 && reagent.ID != MixtureReagent)
                reagents.Add(reagent);
        }

        // Ingredients first, then modifiers, by name inside the groups; the base is inserted before them
        reagents.Sort((a, b) =>
        {
            var byKind = HasCarrier(b).CompareTo(HasCarrier(a));
            return byKind != 0
                ? byKind
                : string.Compare(a.LocalizedName, b.LocalizedName, StringComparison.CurrentCulture);
        });

        if (reagents.Count == 0)
        {
            var empty = new RichTextLabel();
            empty.SetMarkup(Loc.GetString("ce-guidebook-alchemy-no-ingredients"));
            Palette.AddChild(empty);
            return;
        }

        // The blank alchemy mixture comes first: the real recipe always starts from it
        if (_prototype.TryIndex<ReagentPrototype>(MixtureReagent, out var mixture))
            reagents.Insert(0, mixture);

        foreach (var reagent in reagents)
        {
            var id = new ProtoId<ReagentPrototype>(reagent.ID);
            var isBase = reagent.ID == MixtureReagent;
            var isCarrier = HasCarrier(reagent);

            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
            row.AddChild(MakeSwatch(reagent.SubstanceColor));

            var button = new Button
            {
                Text = reagent.LocalizedName,
                HorizontalExpand = true,
                ToolTip = reagent.LocalizedDescription,
                ClipText = true,
                ToggleMode = true,
            };
            button.OnPressed += _ => Select(id);
            _paletteButtons[id] = button;
            row.AddChild(button);

            if (isBase)
                Select(id);

            var kind = new Label
            {
                Text = Loc.GetString(isBase
                    ? "ce-guidebook-alchemy-kind-base"
                    : isCarrier ? "ce-guidebook-alchemy-kind-ingredient" : "ce-guidebook-alchemy-kind-modifier"),
                FontColorOverride = isBase ? MutedColor : isCarrier ? PositionColor : ModifierColor,
                MinWidth = 90,
                Align = Label.AlignMode.Right,
                VerticalAlignment = VAlignment.Center,
            };
            row.AddChild(kind);

            Palette.AddChild(row);
        }
    }

    private void Select(ProtoId<ReagentPrototype> id)
    {
        _selected = id;

        // Only the selected button looks pressed
        foreach (var (reagent, button) in _paletteButtons)
        {
            button.Pressed = reagent == id;
        }

        AddButton.Disabled = false;
        UpdatePreview();
    }

    private static bool HasCarrier(ReagentPrototype reagent)
    {
        foreach (var effect in reagent.AlchemyEffects)
        {
            if (effect is CoordinatePoint)
                return true;
        }

        return false;
    }

    private static Control MakeSwatch(Color color)
    {
        var panel = new PanelContainer
        {
            MinSize = new Vector2(10, 10),
            Margin = new Thickness(2, 3, 6, 3),
            VerticalAlignment = VAlignment.Center,
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = color,
                BorderColor = Color.White.WithAlpha(0.5f),
                BorderThickness = new Thickness(1),
            },
        };
        return panel;
    }

    private void AddStep(ProtoId<ReagentPrototype> reagent)
    {
        if (_steps.Count >= CEAlchemyData.MaxSteps)
            return;

        _steps.Add((reagent, FixedPoint2.New(_amount)));
        Rebuild();
    }

    private CEAlchemyData BuildData()
    {
        var data = new CEAlchemyData { Tune = FixedPoint2.New(_tune) };
        foreach (var (reagent, amount) in _steps)
        {
            data.Steps.Add(new CEAlchemyMixStep { Reagent = reagent, Amount = amount });
        }

        return data;
    }

    private void Rebuild()
    {
        var data = BuildData();
        var trail = new List<Vector2>();
        var state = _alchemy.Replay(data, trail);
        var hits = _alchemy.Analyze(data);

        UpdateDoseSlider(data);
        RefreshMap(trail, state);
        RefreshSteps();
        RefreshHits(hits, state, data);
        RefreshTune(data);

        UpdatePreview();

        CopyButton.Disabled = _steps.Count == 0;
    }

    /// <summary>
    /// Replays the recipe with the selected pour appended and shows the marker move it would cause.
    /// </summary>
    private void UpdatePreview()
    {
        if (_selected is not { } selected || _steps.Count >= CEAlchemyData.MaxSteps)
        {
            Map.SetPreview(null);
            return;
        }

        var data = BuildData();
        data.Steps.Add(new CEAlchemyMixStep { Reagent = selected, Amount = FixedPoint2.New(_amount) });

        var trail = new List<Vector2>();
        _alchemy.Replay(data, trail);

        if (trail.Count < 2 || Vector2.DistanceSquared(trail[^2], trail[^1]) < 0.00001f)
        {
            Map.SetPreview(null);
            return;
        }

        Map.SetPreview((trail[^2], trail[^1]));
    }

    private void RefreshMap(List<Vector2> trail, CEAlchemyState state)
    {
        var dots = new List<CEAlchemyMapControl.MapDot>();
        foreach (var reagent in _prototype.EnumeratePrototypes<ReagentPrototype>())
        {
            foreach (var effect in reagent.AlchemyEffects)
            {
                if (effect is not CoordinatePoint point)
                    continue;

                var pos = _alchemy.GetCarrierPosition(new ProtoId<ReagentPrototype>(reagent.ID), point);
                dots.Add(new CEAlchemyMapControl.MapDot(reagent.ID, reagent.LocalizedName, pos, reagent.SubstanceColor));
            }
        }

        var zones = new List<CEAlchemyMapControl.MapZone>();
        foreach (var zone in _prototype.EnumeratePrototypes<CEAlchemyZonePrototype>())
        {
            zones.Add(new CEAlchemyMapControl.MapZone(
                Loc.GetString(zone.Name),
                _alchemy.GetZonePosition(zone),
                zone.Radius,
                zone.ByPath));
        }

        Map.SetStatic(dots, zones);
        Map.SetPath(trail, state.Carriers > 0 ? state.Pos : null);

        MapLegend.SetMarkup(Loc.GetString("ce-guidebook-alchemy-legend",
            ("position", PositionColor.ToHex()),
            ("path", PathColor.ToHex())));
    }

    private void RefreshSteps()
    {
        StepsBox.RemoveAllChildren();

        if (_steps.Count == 0)
        {
            var hint = new RichTextLabel { Margin = new Thickness(2) };
            hint.SetMarkup(Loc.GetString("ce-guidebook-alchemy-recipe-empty"));
            StepsBox.AddChild(hint);
            return;
        }

        for (var i = 0; i < _steps.Count; i++)
        {
            var (reagentId, amount) = _steps[i];
            if (!_prototype.TryIndex(reagentId, out var reagent))
                continue;

            var index = i;
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
            row.AddChild(new Label
            {
                Text = $"{i + 1}.",
                FontColorOverride = MutedColor,
                MinWidth = 26,
                Align = Label.AlignMode.Right,
                Margin = new Thickness(0, 0, 6, 0),
            });
            row.AddChild(MakeSwatch(reagent.SubstanceColor));
            row.AddChild(new Label
            {
                Text = $"{reagent.LocalizedName} × {FormatAmount(amount.Float())}",
                HorizontalExpand = true,
                ClipText = true,
            });

            var remove = new Button { Text = "✕", MinWidth = 26 };
            remove.OnPressed += _ =>
            {
                _steps.RemoveAt(index);
                Rebuild();
            };
            row.AddChild(remove);

            StepsBox.AddChild(row);
        }
    }

    private void RefreshHits(List<CEAlchemyHit> hits, CEAlchemyState state, CEAlchemyData data)
    {
        HitsBox.RemoveAllChildren();

        if (_steps.Count == 0 || state.Carriers <= 0 || hits.Count == 0)
        {
            var none = new RichTextLabel();
            none.SetMarkup(Loc.GetString("ce-guidebook-alchemy-result-none"));
            HitsBox.AddChild(none);
        }

        foreach (var hit in hits)
        {
            HitsBox.AddChild(MakeHitCard(hit, GetDuration(data)));
        }

    }

    /// <summary>
    /// The dose can be anything from nothing to the whole recipe volume. By default it follows the whole volume.
    /// </summary>
    private void UpdateDoseSlider(CEAlchemyData data)
    {
        var total = data.TotalAmount.Float();
        if (_doseFollowsMax || _dose > total)
            _dose = total;

        _updatingDose = true;
        DoseSlider.MaxValue = MathF.Max(total, 0.1f);
        DoseSlider.Value = _dose;
        DoseSlider.Disabled = total <= 0;
        _updatingDose = false;

        DoseLabel.Text = Loc.GetString("ce-guidebook-alchemy-dose-value", ("value", FormatAmount(_dose)));
    }

    /// <summary>
    /// How long the accepted dose of this mixture works: it is metabolized at a fixed rate multiplied by the tuning.
    /// </summary>
    private TimeSpan GetDuration(CEAlchemyData data) => _alchemy.GetDuration(data, FixedPoint2.New(_dose));

    private string FormatDuration(TimeSpan duration) => _alchemy.FormatDuration(duration);

    private Control MakeHitCard(CEAlchemyHit hit, TimeSpan duration)
    {
        var color = hit.Zone.ByPath ? PathColor : PositionColor;

        var card = new PanelContainer
        {
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = color.WithAlpha(0.1f),
                BorderColor = color.WithAlpha(0.55f),
                BorderThickness = new Thickness(1),
            },
        };

        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(8, 5),
        };
        card.AddChild(box);

        box.AddChild(new Label
        {
            Text = Loc.GetString(hit.Zone.Name),
            FontColorOverride = color,
        });

        var placeholder = Loc.GetString("ce-entity-effect-guidebook-none");
        var durationText = FormatDuration(duration);
        foreach (var effect in hit.Zone.Effects)
        {
            var text = effect.EntityEffectGuidebookText(_prototype, _entSys, hit.Strength);
            if (string.IsNullOrWhiteSpace(text) || text == placeholder)
                continue;

            // A status effect is refreshed every second and has its own duration, the rest works every second.
            text = text.TrimEnd('.', ' ');
            var line = Loc.GetString(effect is ApplyStatusEffect
                    ? "ce-guidebook-alchemy-effect-line-status"
                    : "ce-guidebook-alchemy-effect-line",
                ("effect", text),
                ("duration", durationText));

            var label = new RichTextLabel { Margin = new Thickness(0, 2, 0, 0) };
            label.SetMarkup(line);
            box.AddChild(label);
        }

        return card;
    }

    private void RefreshTune(CEAlchemyData data)
    {
        var sign = _tune > 0 ? "+" : string.Empty;
        TuneLabel.SetMarkup(Loc.GetString("ce-guidebook-alchemy-tune-value",
            ("tune", sign + _tune.ToString("0.00", CultureInfo.InvariantCulture)),
            ("multiplier", data.Multiplier.ToString("0.00", CultureInfo.InvariantCulture))));
    }

    private string BuildRecipeText()
    {
        var total = 0f;
        foreach (var (_, amount) in _steps)
        {
            total += amount.Float();
        }

        // The recipe is scaled to the dose chosen by the user
        var batch = _dose > 0 ? _dose : total;
        var builder = new StringBuilder();
        builder.AppendLine(Loc.GetString("ce-guidebook-alchemy-copy-header", ("batch", FormatAmount(batch))));

        if (total <= 0)
            return builder.ToString().TrimEnd();

        for (var i = 0; i < _steps.Count; i++)
        {
            var (reagentId, amount) = _steps[i];
            if (!_prototype.TryIndex(reagentId, out var reagent))
            {
                _sawmill.Warning($"Unknown reagent {reagentId} in the sandbox recipe");
                continue;
            }

            var scaled = amount.Float() / total * batch;
            builder.AppendLine(Loc.GetString("ce-guidebook-alchemy-copy-line",
                ("index", i + 1),
                ("reagent", reagent.LocalizedName),
                ("amount", FormatAmount(scaled))));
        }

        if (MathF.Abs(_tune) > 0.001f)
        {
            var sign = _tune > 0 ? "+" : string.Empty;
            builder.AppendLine(Loc.GetString("ce-guidebook-alchemy-copy-tune",
                ("tune", sign + _tune.ToString("0.00", CultureInfo.InvariantCulture))));
        }

        var data = BuildData();
        var duration = FormatDuration(GetDuration(data));
        var placeholder = Loc.GetString("ce-entity-effect-guidebook-none");
        var effectsHeader = false;
        foreach (var hit in _alchemy.Analyze(data))
        {
            var lines = new List<string>();
            foreach (var effect in hit.Zone.Effects)
            {
                var text = effect.EntityEffectGuidebookText(_prototype, _entSys, hit.Strength);
                if (string.IsNullOrWhiteSpace(text) || text == placeholder)
                    continue;

                text = text.TrimEnd('.', ' ');
                lines.Add(Loc.GetString(effect is ApplyStatusEffect
                        ? "ce-guidebook-alchemy-effect-line-status"
                        : "ce-guidebook-alchemy-effect-line",
                    ("effect", text),
                    ("duration", duration)));
            }

            if (lines.Count == 0)
                continue;

            if (!effectsHeader)
            {
                builder.AppendLine();
                builder.AppendLine(Loc.GetString("ce-guidebook-alchemy-copy-effects"));
                effectsHeader = true;
            }

            builder.AppendLine(Loc.GetString("ce-guidebook-alchemy-copy-effect",
                ("zone", Loc.GetString(hit.Zone.Name)),
                ("effects", string.Join(" ", lines))));
        }

        return builder.ToString().TrimEnd();
    }

    private static string FormatAmount(float value)
    {
        return MathF.Round(value, 1).ToString("0.#", CultureInfo.InvariantCulture);
    }
}
