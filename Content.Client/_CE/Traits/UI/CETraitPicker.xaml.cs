using System.Linq;
using Content.Client._CE.Skill;
using Content.Client.Players.PlayTimeTracking;
using Content.Shared._CE.Traits;
using Content.Shared.Preferences;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._CE.Traits.UI;

/// <summary>
/// Lobby trait tab: the rules with the current balance on top, a grid of trait tiles and a details
/// panel describing the hovered trait.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CETraitPicker : BoxContainer
{
    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private IPrototypeManager _proto = default!;
    [Dependency] private JobRequirementsManager _requirements = default!;

    private static readonly Color BalancedColor = Color.FromHex("#4CC35A");
    private static readonly Color UnbalancedColor = Color.FromHex("#E0524C");

    private readonly CEClientSkillSystem _skill;
    private readonly SpriteSystem _sprite;

    private readonly Dictionary<ProtoId<CETraitPrototype>, CETraitButton> _buttons = new();
    private readonly Dictionary<ProtoId<CETraitPrototype>, FormattedMessage> _lockReasons = new();
    private HashSet<ProtoId<CETraitPrototype>> _selected = new();
    private ProtoId<CETraitPrototype>? _hovered;

    /// <summary>
    /// Raised when a trait tile is clicked, with whether the trait should now be picked.
    /// </summary>
    public event Action<ProtoId<CETraitPrototype>, bool>? OnTraitToggled;

    public CETraitPicker()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _skill = _entMan.System<CEClientSkillSystem>();
        _sprite = _entMan.System<SpriteSystem>();

        RulesLabel.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString("ce-trait-rules")));
    }

    /// <summary>
    /// Rebuilds the grid - call when the profile, trait prototypes or unlocks change.
    /// </summary>
    public void Populate(HumanoidCharacterProfile? profile)
    {
        TraitGrid.RemoveAllChildren();
        _buttons.Clear();
        _lockReasons.Clear();

        var entries = new List<(CETraitPrototype Trait, string Name, bool Locked)>();
        foreach (var trait in _proto.EnumeratePrototypes<CETraitPrototype>())
        {
            var locked = !_requirements.IsAllowed(trait, profile, out var reason);
            if (locked)
                _lockReasons[trait.ID] = reason!;

            entries.Add((trait, _skill.GetSkillName(trait.Skill), locked));
        }

        // Locked traits always sink to the bottom; the rest go from the most beneficial to the most harmful.
        var ordered = entries
            .OrderBy(e => e.Locked)
            .ThenByDescending(e => e.Locked ? 0 : e.Trait.Cost)
            .ThenBy(e => e.Name, StringComparer.CurrentCultureIgnoreCase);

        foreach (var (trait, _, _) in ordered)
        {
            var id = new ProtoId<CETraitPrototype>(trait.ID);
            var button = new CETraitButton(id, GetIcon(trait), trait.Cost);

            button.OnPressed += _ => OnTraitToggled?.Invoke(id, !_selected.Contains(id));
            button.OnMouseEntered += _ => SetHovered(id);
            button.OnMouseExited += _ =>
            {
                if (_hovered == id)
                    SetHovered(null);
            };

            _buttons[id] = button;
            TraitGrid.AddChild(button);
        }

        EmptyLabel.Visible = _buttons.Count == 0;
        TraitGrid.Parent!.Visible = _buttons.Count > 0;

        if (_hovered is { } hovered && !_buttons.ContainsKey(hovered))
            _hovered = null;

        SetSelection(profile?.TraitPreferences ?? new HashSet<ProtoId<CETraitPrototype>>());
    }

    /// <summary>
    /// Updates tile states and the balance after the picked traits changed, without rebuilding the grid.
    /// </summary>
    public void SetSelection(IReadOnlySet<ProtoId<CETraitPrototype>> selected)
    {
        _selected = new HashSet<ProtoId<CETraitPrototype>>(selected);

        foreach (var (id, button) in _buttons)
        {
            var isSelected = _selected.Contains(id);
            button.SetState(isSelected, _lockReasons.ContainsKey(id), !isSelected && ConflictsWithSelection(id));
        }

        var balance = CETraitRules.GetBalance(_selected, _proto);
        BalanceLabel.Text = CETraitButton.FormatCost(balance);
        BalanceLabel.FontColorOverride = CETraitRules.IsSelectionValid(_selected, _proto) ? BalancedColor : UnbalancedColor;

        UpdateDetails();
    }

    private bool ConflictsWithSelection(ProtoId<CETraitPrototype> trait)
    {
        foreach (var other in _selected)
        {
            if (CETraitRules.AreIncompatible(trait, other, _proto))
                return true;
        }

        return false;
    }

    private void SetHovered(ProtoId<CETraitPrototype>? trait)
    {
        _hovered = trait;
        UpdateDetails();
    }

    private void UpdateDetails()
    {
        if (_hovered is not { } id || !_proto.Resolve(id, out var trait))
        {
            DetailsBox.Visible = false;
            DetailsHint.Visible = true;
            return;
        }

        DetailsBox.Visible = true;
        DetailsHint.Visible = false;

        var locked = _lockReasons.TryGetValue(id, out var lockReason);

        DetailsIcon.Texture = GetIcon(trait);
        DetailsIcon.Modulate = locked ? Color.Black : Color.White;
        DetailsName.SetMessage(FormattedMessage.FromMarkupPermissive(
            $"[bold]{FormattedMessage.EscapeText(_skill.GetSkillName(trait.Skill))}[/bold]"));

        // A locked trait shows only its unlock condition - its cost and effect stay a surprise.
        DetailsCost.Visible = !locked;
        DetailsCost.Text = Loc.GetString("ce-trait-cost", ("cost", CETraitButton.FormatCost(trait.Cost)));
        DetailsCost.FontColorOverride = CETraitButton.CostColor(trait.Cost);

        DetailsDescription.SetMessage(locked
            ? lockReason!
            : FormattedMessage.FromMarkupPermissive(_skill.GetSkillDescription(trait.Skill)));

        var extra = new FormattedMessage();
        if (!locked && trait.Gear is { } gear && _proto.TryIndex(gear, out var gearProto))
        {
            extra.PushColor(Color.FromHex("#A0A0B0"));
            extra.AddText(Loc.GetString("ce-trait-gear", ("item", gearProto.Name)));
            extra.Pop();
        }

        var conflicts = _buttons.Keys
            .Where(other => other != id && CETraitRules.AreIncompatible(id, other, _proto))
            .ToList();

        if (conflicts.Count > 0)
        {
            if (!extra.IsEmpty)
                extra.PushNewline();

            var names = string.Join(", ", conflicts.Select(c => _skill.GetSkillName(_proto.Index(c).Skill)));
            extra.PushColor(conflicts.Any(_selected.Contains) ? UnbalancedColor : Color.FromHex("#A0A0B0"));
            extra.AddText(Loc.GetString("ce-trait-incompatible", ("traits", names)));
            extra.Pop();
        }

        DetailsExtra.Visible = !extra.IsEmpty;
        DetailsExtra.SetMessage(extra);
    }

    private Texture? GetIcon(CETraitPrototype trait)
    {
        if (_skill.GetSkillIcon(trait.Skill) is { } icon)
            return _sprite.Frame0(icon);

        return _skill.GetSkillPreviewEntity(trait.Skill) is { } preview ? _sprite.Frame0(preview) : null;
    }
}
