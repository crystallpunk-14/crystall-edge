using Content.Client._CE.UserInterface;
using Content.Shared._CE.Trade;
using Content.Shared._CE.Trade.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._CE.Trade;

/// <summary>
/// One exchange of a trade shop window: what the user gives, what they get and the trade button.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CETradeShopOfferControl : Control
{
    [Dependency] private IEntityManager _entity = default!;
    [Dependency] private IPrototypeManager _prototype = default!;

    public event Action<ProtoId<CETradeOfferPrototype>>? OnTrade;

    public CETradeShopOfferControl(CETradeShopEntry entry, CETradeOfferPrototype offer)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        var trade = _entity.System<CESharedTradeSystem>();

        foreach (var cost in offer.Cost)
        {
            GiveBox.AddChild(new Label { Text = cost.GetRequirementTitle(_prototype) });
        }

        if (entry.PayPrice > 0)
            GiveBox.AddChild(new CEPriceControl(entry.PayPrice));

        GetBox.AddChild(new Label { Text = trade.GetOfferName(offer) });
        if (entry.ReceivePrice > 0)
            GetBox.AddChild(new CEPriceControl(entry.ReceivePrice));

        Preview.SetPrototype(trade.GetPreview(offer, entry.ReceivePrice));

        var available = entry.Missing is null;
        TradeButton.Disabled = !available;
        if (!available)
        {
            TradeButton.ToolTip = Loc.GetString("ce-trade-missing", ("items", entry.Missing!));
            Modulate = Color.FromHex("#a0a0a0");
        }

        TradeButton.OnPressed += _ => OnTrade?.Invoke(offer.ID);
    }
}
